#!/usr/bin/env bash
# cmd/build.sh - turn the manifests into frontend + emulator configuration.
#
# Everything this writes is generated. Edit config/*.yaml and re-run; never
# hand-edit the output.

cmd_build() {
  local install=1 do_ra=1 do_dirs=1 only="" apply_ra=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --no-install)   install=0 ;;
      --no-retroarch) do_ra=0 ;;
      --no-dirs)      do_dirs=0 ;;
      --apply-retroarch) apply_ra=1 ;;
      --systems)      only="${2:-}"; shift ;;
      -h|--help)
        cat >&2 <<'__H__'
retropi build - generate frontend and emulator configuration

  --no-install      write to build/ only, do not install into the frontend
  --no-retroarch    skip RetroArch path configuration
  --no-dirs         do not create the ROM directory tree
  --systems <ids>   build only these systems (comma separated)
  --apply-retroarch merge the generated keys into your real retroarch.cfg
                    (the original is backed up first)

Output lands in build/ and is installed to the frontend config directory.
Existing files are backed up before being replaced.
__H__
        return 0 ;;
      *) die "build: unknown option $1" ;;
    esac
    shift
  done

  local out ids
  out="$(build_dir)"
  ensure_dir "$out"

  if [[ -n "$only" ]]; then
    ids="$(printf '%s' "$only" | tr ',' '\n')"
  else
    ids="$(systems_enabled)"
  fi
  [[ -n "$ids" ]] || die "no systems enabled; check systems.enabled in your config"

  [[ "$do_dirs" == "1" ]] && _build_rom_dirs "$ids"
  _build_es_systems "$ids" "$out"
  [[ "$do_ra" == "1" ]] && _build_retroarch "$out"
  [[ "$install" == "1" ]] && _install_generated "$out"
  [[ "$apply_ra" == "1" ]] && _apply_retroarch "$out"

  info "build complete"
  step "generated files: $out"
  [[ "$install" == "1" ]] && step "installed to: $(es_config_dir)"
  log ""
  log "Next: put games in $(roms_dir)/<system>/ and start your frontend."
  return 0
}

# --- ROM directory tree -------------------------------------------------------

_build_rom_dirs() {
  local ids="$1" id dir n=0
  info "creating ROM directories"
  while IFS= read -r id; do
    [[ -n "$id" ]] || continue
    id="$(system_resolve "$id")" || { warn "unknown system: $id"; continue; }
    dir="$(system_rom_dir "$id")"
    if [[ ! -d "$dir" ]]; then
      ensure_dir "$dir"
      n=$((n+1))
    fi
    _write_rom_readme "$id" "$dir"
  done <<< "$ids"
  ok "ROM tree ready under $(roms_dir) ($n new)"
}

# A short note in each folder so the tree explains itself on any machine.
_write_rom_readme() {
  local id="$1" dir="$2" f="$2/_ABOUT.txt"
  [[ "$RETROPI_DRY_RUN" == "1" ]] && return 0
  [[ -f "$f" ]] && return 0
  {
    printf '%s (%s)\n' "$(sys_get "$id" name)" "$id"
    printf '%s\n\n' "$(printf '%s' "$(sys_get "$id" name)" | sed 's/./=/g')"
    printf 'Put %s games in this folder.\n\n' "$(sys_get "$id" short_name "$id")"
    printf 'Accepted file types: %s\n' "$(sys_list "$id" extensions | tr '\n' ' ')"
    printf 'Default emulator:    %s\n' "$(default_emulator "$id" || printf 'none available')"
    local notes
    notes="$(sys_get "$id" notes "")"
    [[ -n "$notes" ]] && printf '\nNotes: %s\n' "$notes"
    printf '\nThis file is generated by `retropi build`.\n'
  } > "$f"
}

# --- es_systems.xml -----------------------------------------------------------
# One format understood by both ES-DE (macOS/Linux) and RetroPie's
# EmulationStation. Alternate emulators are emitted as extra <command label=>
# entries: ES-DE shows them in a picker, RetroPie ES uses the first.

_build_es_systems() {
  local ids="$1" out="$2" xml="$2/es_systems.xml"
  info "generating es_systems.xml"
  local id count=0

  {
    printf '<?xml version="1.0" encoding="UTF-8"?>\n'
    printf '<!-- Generated by retropi %s on %s for %s.\n' \
      "$RETROPI_VERSION" "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$(platform_label)"
    printf '     Do not edit: change config/systems/*.yaml and re-run `retropi build`. -->\n'
    printf '<systemList>\n'
  } > "$xml"

  while IFS= read -r id; do
    [[ -n "$id" ]] || continue
    id="$(system_resolve "$id")" || { warn "unknown system: $id"; continue; }
    _es_system_entry "$id" >> "$xml"
    count=$((count+1))
  done <<< "$ids"

  printf '</systemList>\n' >> "$xml"
  ok "$count systems written to $xml"
}

_es_system_entry() {
  local id="$1" name path ext plat theme idx emu label cmdline default_emu
  name="$(sys_get "$id" name "$id")"
  path="$(system_rom_dir "$id")"
  ext="$(system_extensions "$id")"
  plat="$(sys_get "$id" frontend.platform "$id")"
  theme="$(sys_get "$id" frontend.theme "$plat")"
  default_emu="$(default_emulator "$id" || printf '')"

  printf '  <system>\n'
  printf '    <name>%s</name>\n' "$(xml_escape "$id")"
  printf '    <fullname>%s</fullname>\n' "$(xml_escape "$name")"
  printf '    <path>%s</path>\n' "$(xml_escape "$path")"
  printf '    <extension>%s</extension>\n' "$(xml_escape "$ext")"

  if [[ -z "$default_emu" ]]; then
    warn "$id: no emulator available on $(platform_label); emitting system without a command"
  else
    # Default first so RetroPie ES (which reads only the first) gets the right one.
    cmdline="$(launch_command "$id" "$default_emu")"
    idx="$(emulator_index_of "$id" "$default_emu")"
    label="$(emulator_field "$id" "$idx" display "$default_emu")"
    printf '    <command label="%s">%s</command>\n' \
      "$(xml_escape "$label")" "$(xml_escape "$cmdline")"

    while IFS= read -r idx; do
      [[ -n "$idx" ]] || continue
      emu="$(emulator_field "$id" "$idx" id)"
      [[ "$emu" == "$default_emu" ]] && continue
      emulator_supported "$id" "$idx" || continue
      cmdline="$(launch_command "$id" "$emu")" || continue
      label="$(emulator_field "$id" "$idx" display "$emu")"
      printf '    <command label="%s">%s</command>\n' \
        "$(xml_escape "$label")" "$(xml_escape "$cmdline")"
    done < <(emulator_indices "$id")
  fi

  printf '    <platform>%s</platform>\n' "$(xml_escape "$plat")"
  printf '    <theme>%s</theme>\n' "$(xml_escape "$theme")"
  printf '  </system>\n'
}

# --- RetroArch ----------------------------------------------------------------
# Saves, states and screenshots are centralized so the ROM tree stays a clean
# mirror you can re-sync without losing progress.

_build_retroarch() {
  local out="$1" cfg="$1/retroarch-retropi.cfg"
  info "generating RetroArch overrides"
  ensure_dir "$(saves_dir)" "$(screenshots_dir)"

  {
    printf '# Generated by retropi %s - do not edit.\n' "$RETROPI_VERSION"
    printf '# Applied on top of your retroarch.cfg by `retropi build`.\n\n'
    if [[ "$(cfg saves.centralize true)" == "true" ]]; then
      printf 'savefile_directory = "%s"\n' "$(saves_dir)"
      printf 'savestate_directory = "%s"\n' "$(saves_dir)"
    fi
    printf 'screenshot_directory = "%s"\n' "$(screenshots_dir)"
    printf 'system_directory = "%s"\n' "$(bios_dir)"
    printf 'rgui_browser_directory = "%s"\n' "$(roms_dir)"
    printf 'savestate_auto_save = "%s"\n' "$(cfg saves.auto_save_state false)"
    printf 'savestate_auto_load = "%s"\n' "$(cfg saves.auto_save_state false)"
    printf 'rewind_enable = "%s"\n' "$(cfg saves.rewind_enabled true)"
    if [[ "$(cfg controls.manage_autoconfig true)" == "true" ]]; then
      printf '\n# hotkeys (hold %s)\n' "$(cfg controls.hotkey_enable select)"
      printf 'input_enable_hotkey_btn = "%s"\n' "$(_ra_btn "$(cfg controls.hotkey_enable select)")"
      local k v
      for k in $(cfg_keys controls.hotkeys); do
        v="$(cfg "controls.hotkeys.$k")"
        printf 'input_%s_btn = "%s"\n' "$(_ra_hotkey_name "$k")" "$(_ra_btn "$v")"
      done
    fi
  } > "$cfg"
  ok "wrote $cfg"
}

# RetroArch names hotkey actions differently from our friendly config keys.
_ra_hotkey_name() {
  case "$1" in
    exit)        printf 'exit_emulator' ;;
    menu)        printf 'menu_toggle' ;;
    save_state)  printf 'save_state' ;;
    load_state)  printf 'load_state' ;;
    screenshot)  printf 'screenshot' ;;
    rewind)      printf 'rewind' ;;
    *)           printf '%s' "$1" ;;
  esac
}

# Map friendly button names to RetroArch's numeric pad indices.
_ra_btn() {
  case "$1" in
    a) printf '0' ;; b) printf '1' ;; x) printf '2' ;; y) printf '3' ;;
    l|l1) printf '4' ;; r|r1) printf '5' ;;
    select) printf '6' ;; start) printf '7' ;;
    nul) printf 'nul' ;;
    *) printf '%s' "$1" ;;
  esac
}

# _apply_retroarch <build_dir> - merge generated keys into the live
# retroarch.cfg: replace keys that exist, append the ones that do not, leave
# every other user setting untouched.
_apply_retroarch() {
  local out="$1" gen="$1/retroarch-retropi.cfg" target
  target="$(retroarch_config_dir)/retroarch.cfg"
  [[ -f "$gen" ]] || die "nothing generated to apply; run without --no-retroarch"

  if [[ ! -f "$target" ]]; then
    warn "no retroarch.cfg at $target (start RetroArch once to create it)"
    ensure_dir "$(dirname "$target")"
    run cp "$gen" "$target"
    ok "seeded $target"
    return 0
  fi

  info "merging RetroArch settings into $target"
  backup_file "$target"
  if [[ "$RETROPI_DRY_RUN" == "1" ]]; then
    step "dry run: would update $(grep -c '^[a-z_]* = ' "$gen") keys"
    return 0
  fi
  python3 - "$gen" "$target" <<'__PY__'
import re, sys
gen, target = sys.argv[1], sys.argv[2]
wanted = {}
for line in open(gen, encoding="utf-8"):
    m = re.match(r'^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$', line)
    if m and not line.lstrip().startswith("#"):
        wanted[m.group(1)] = m.group(2)

out, seen = [], set()
for line in open(target, encoding="utf-8"):
    m = re.match(r'^\s*([A-Za-z0-9_]+)\s*=', line)
    if m and m.group(1) in wanted:
        key = m.group(1)
        out.append(f"{key} = {wanted[key]}\n")
        seen.add(key)
    else:
        out.append(line)

missing = [k for k in wanted if k not in seen]
if missing:
    if out and not out[-1].endswith("\n"):
        out.append("\n")
    out.append("\n# --- added by retropi ---\n")
    out.extend(f"{k} = {wanted[k]}\n" for k in missing)

open(target, "w", encoding="utf-8").writelines(out)
print(f"updated {len(seen)} keys, added {len(missing)}")
__PY__
  ok "retroarch.cfg updated"
}

# --- install ------------------------------------------------------------------

_install_generated() {
  local out="$1" dest xml
  dest="$(es_config_dir)"
  xml="$out/es_systems.xml"
  info "installing frontend configuration"
  ensure_dir "$dest"
  backup_file "$dest/es_systems.xml"
  run cp "$xml" "$dest/es_systems.xml"
  ok "installed $dest/es_systems.xml"

  local racfg radir
  radir="$(retroarch_config_dir)"
  racfg="$radir/retroarch.cfg"
  if [[ -d "$radir" && -f "$out/retroarch-retropi.cfg" ]]; then
    run cp "$out/retroarch-retropi.cfg" "$radir/retropi.cfg"
    ok "copied RetroArch overrides to $radir/retropi.cfg"
    if [[ -f "$racfg" ]]; then
      warn "RetroArch has no include directive; merge $radir/retropi.cfg into retroarch.cfg"
      step "merge them automatically: ./bin/retropi build --apply-retroarch"
    fi
  else
    debug "RetroArch config dir not present yet: $radir"
  fi
}
