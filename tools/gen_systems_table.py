#!/usr/bin/env python3
"""Generate the platform table in docs/systems/README.md from systems/registry.yaml.

The registry is the one definition of every system id (see AGENTS.md); the
encyclopedia's table of ids, names, years, media and per-pillar support used to
be a hand copy of it. This rewrites the span between

    <!-- AUTO:systems:start -->
    <!-- AUTO:systems:end -->

from the registry, so the two can no longer disagree. The prose around the
span, and the family pages it links to, stay hand-written.

The registry is read with the same rules as arcade/src/systems/parse.ts: a
flat list of mappings, `- id:` opening each entry, quoted or bare scalars.

Usage:
    python3 tools/gen_systems_table.py            # rewrite the span
    python3 tools/gen_systems_table.py --check    # exit 1 when it is stale

Standard library only; `make test` and `make check` run the check.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = "systems/registry.yaml"
DOC = "docs/systems/README.md"
COMMAND = "python3 tools/gen_systems_table.py"
START = "<!-- AUTO:systems:start -->"
END = "<!-- AUTO:systems:end -->"
FLAGS = ("arcade", "emulate", "emulate_enabled", "identify", "catalog")


def unquote(raw: str) -> str:
    value = raw.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse(text: str) -> list[dict]:
    systems: list[dict] = []
    current: dict | None = None
    for raw in text.splitlines():
        line = raw.rstrip()
        if not line or line.lstrip().startswith("#"):
            continue
        m = re.match(r"^\s*-\s+id:\s*(.+)$", line)
        if m:
            current = {"id": unquote(m.group(1))}
            systems.append(current)
            continue
        m = re.match(r"^\s+([A-Za-z_]+):\s*(.*)$", line)
        if m and current is not None:
            current[m.group(1)] = unquote(m.group(2))
    for s in systems:
        for flag in FLAGS:
            s[flag] = s.get(flag, "false") == "true"
        s.setdefault("manufacturer", "Various")
        s.setdefault("name", s["id"])
    return systems


def render(systems: list[dict]) -> str:
    def mark(value: bool) -> str:
        return "yes" if value else "—"

    def count(flag: str) -> int:
        return sum(1 for s in systems if s[flag])

    ordered = sorted(
        systems, key=lambda s: (s["manufacturer"].lower(), int(s.get("year") or 0), s["id"])
    )
    out = [
        START,
        "<!-- GENERATED by %s — do not edit by hand. Edit %s and rerun it. -->" % (COMMAND, REGISTRY),
        "",
        "%d platform ids: %d browser recreations, %d with an emulate manifest (%d enabled in a fresh"
        " build), %d identifiable from dump bytes, %d inventory and price-guide platforms."
        % (
            len(systems),
            count("arcade"),
            count("emulate"),
            count("emulate_enabled"),
            count("identify"),
            count("catalog"),
        ),
        "",
        "| id | Name | Manufacturer | Year | Media | Play | Emu | On | ID | Cat |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for s in ordered:
        out.append(
            "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |"
            % (
                s["id"],
                s["name"].replace("|", "\\|"),
                s["manufacturer"],
                s.get("year", ""),
                s.get("media", ""),
                mark(s["arcade"]),
                mark(s["emulate"]),
                mark(s["emulate_enabled"]),
                mark(s["identify"]),
                mark(s["catalog"]),
            )
        )
    out.append(END)
    return "\n".join(out)


def rebuild(doc: str, span: str) -> str:
    start = doc.find(START)
    end = doc.find(END, start)
    if start < 0 or end < 0:
        raise SystemExit("%s has no %s … %s span" % (DOC, START, END))
    return doc[:start] + span + doc[end + len(END):]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the table is stale")
    args = parser.parse_args(argv)
    with open(os.path.join(ROOT, REGISTRY), encoding="utf-8") as fh:
        systems = parse(fh.read())
    path = os.path.join(ROOT, DOC)
    with open(path, encoding="utf-8") as fh:
        current = fh.read()
    fresh = rebuild(current, render(systems))
    if args.check:
        if fresh != current:
            print("%s is stale: run %s" % (DOC, COMMAND), file=sys.stderr)
            return 1
        print("%s is current" % DOC)
        return 0
    if fresh != current:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(fresh)
        print("wrote %s" % DOC)
    else:
        print("%s already current" % DOC)
    return 0


if __name__ == "__main__":
    sys.exit(main())
